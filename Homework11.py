import os
import dotenv

from langchain_google_genai import GoogleGenerativeAI
from langchain.prompts import PromptTemplate

# завантаження апі ключа
dotenv.load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")

# створити llm
llm = GoogleGenerativeAI(
    model='gemma-3-1b-it',
    api_key=api_key,
    temperature=0
)

# prompt = PromptTemplate.from_template("""
#     Ти - составник навчального курсу з певної теми для певної цільової аудиторії.
#     Твоє завдання сгенерувати навчальний курс на задану тему для різних цільових аудиторій(початківці, професіонали, діти, тощо).
#     Тема і цільова аудиторія буде вказана нижче.
#
#     ### ТЕМА
#     {theme}
#
#     ### ЦІЛЬОВА АУДІТОРІЯ
#     {target_audience}
#
#     """)

prompt = PromptTemplate.from_template("""
    Ти - составник навчального курсу з певної теми для певної цільової аудиторії. 
    Твоє завдання сгенерувати навчальний курс на задану тему для різних цільових аудиторій(початківці, професіонали, діти, тощо).
    Тема і цільова аудиторія буде вказана нижче.

    ### ПРИКЛАД
    ТЕМА: йога
    ЦІЛЬОВА АУДИТОРІЯ: діти
    ВІДПОВІДЬ:
    Навчальний курс: Йога для Дітей (6-12 років)
    
    **Мета курсу:** Забезпечити дітям базові знання про йогу, її переваги та способи її інтеграції в повсякденне життя.
    
    **Цільова аудиторія:** Діти 6-12 років.
    
    **Тривалість:** 60-90 хвилин (можна адаптувати)
    
    **Структура курсу:**
    
    **Розділ 1: Що таке йога? (5-10 хвилин)**
    
    * **Що таке йога?** Пояснення, що йога - це практика, яка поєднує фізичні вправи, дихання та медитацію.
    * **Як йога допомагає тілу?**  Пояснення, що йога покращує гнучкість, силу, координацію та стійкість.
    * **Важливість дихання (пранаями):**  Пояснення, що дихання - це важлива частина йоги, допомагає розслабитися та зняти напругу.
    * **Візуалізація:**  Покажіть короткі відео або картинки, що демонструють дихання та його вплив на тіло.
    
    **Розділ 2:  Фізичні вправи (15-20 хвилин)**
    
    * **Розтяжка:**  Покажіть прості розтяжки для ніг, рук, спини та плечей.  Поясніть, як робити розтяжку правильно, щоб не боліти.
    * **Позиції для розслаблення:**  Покажіть базові позиції, такі як:
        * **Поза "місяць":**  Покажіть, як підняти руки та ноги, щоб створити відчуття "місяця".
        * **Поза "коса":**  Покажіть, як підняти руки та ноги, щоб створити відчуття "коси".
        * **Поза "затишок":**  Покажіть, як підняти руки та ноги, щоб створити відчуття "затишку".
    * **Важливо:**  Підкреслити, що важливо робити розтяжку повільно та обережно, не викликаючи болю.
    
    **Розділ 3:  Дихання (10-15 хвилин)**
    
    * **Пояснення дихання:**  Пояснення, що дихання - це як "повітряний насос".
    * **Вправи на дихання:**  Покажіть прості вправи на дихання, такі як:
        * **Вдих-вихід:**  Покажіть, як вдихати через ніс та видихати через рот.
        * **Вдих-вихід-вдих-вихід:**  Покажіть, як вдихати, видихати, потім вдихати ще раз і видихати ще раз.
    * **Зв'язок з відчуттями:**  Поясніть, що дихання може допомогти відчути себе спокійнішим та більш зосередженим.
    
    **Розділ 4:  Медитація (10-15 хвилин)**
    
    * **Що таке медитація?**  Пояснення, що медитація - це спосіб зосередитися на своєму внутрішньому світі.
    * **Прості медитації:**  Покажіть прості медитації, наприклад, зосередження на диханні або на звуках навколо.
    * **Поради:**  Поясніть, що важливо не критикувати себе, а просто спостерігати за своїми думками та відчуттями.
    
    **Розділ 5:  Завершення (5-10 хвилин)**
    
    * **Повторення:**  Повторіть основні моменти курсу.
    * **Запитання:**  Запитайте дітей, що вони відчули, коли зробили йогу.
    * **Підкреслення:**  Повторіть, що йога - це чудовий спосіб почуватися добре, а не обов'язково бути професіоналом.
    
    **Додаткові поради:**
    
    * **Візуальні матеріали:** Використовуйте багато візуальних матеріалів, таких як відео, картинки та ілюстрації.
    * **Ігри та розваги:**  Додайте ігри та розваги, щоб зробити урок більш цікавим та захопливим.
    * **Приклади:**  Надайте приклади того, як йога може бути інтегрована в повсякденне життя дітей.
    * **Повторення:**  Повторюйте ключові моменти курсу кілька разів.
    
    **Важливо:**  Завжди враховуйте індивідуальні потреби та рівень підготовки дітей.  Забезпечте безпечне та комфортне середовище для практики.
    
    ### ДАНІ ВІД КОРИСТУВАЧА

    ТЕМА: {theme}
    ЦІЛЬОВА АУДИТОРІЯ: {target_audience}
    ВІДПОВІДЬ:

    """)

chain = prompt | llm

theme = input('Введіть тему:')
target_audience = input('Введіть назву цільової аудиторії:')

response = chain.invoke(

    {
        "theme": theme,
        "target_audience": target_audience
    }

)

print(response)
